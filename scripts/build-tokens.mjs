// Gallium · build-tokens.mjs — tokens/*.tokens.json (DTCG 2025.10) are the source of truth.
// Generates the token block of gallium.css between the tokens:start / tokens:end markers.
// Zero dependencies. `--check` exits 1 if gallium.css is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const START = '/* tokens:start', END = '/* tokens:end */';
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));

// DTCG path → CSS custom property name (inverse of the original naming)
const PREFIX = { spacing: 'sp-', radius: 'r-', typography: 'type-', duration: 'dur-', easing: 'ease-', z: 'z-', shadow: 'elev-' };
function cssName(path) {
  const [g, ...rest] = path;
  if (g === 'color') return rest.join('-');                         // color.gray.10 → gray-10, color.white → white
  if (g === 'size') return (rest[0] === 'control' ? 'h-' : 'icon-') + rest[1];
  if (g === 'semantic') return rest.join('-');
  if (PREFIX[g]) return PREFIX[g] + rest.join('-');
  throw new Error('Unknown token group: ' + path.join('.'));
}
const toCss = (v) => String(v).replace(/\{([^}]+)\}/g, (_, p) => `var(--cf-${cssName(p.split('.'))})`);

function walk(node, path = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push({ name: cssName([...path, k]), value: toCss(v.$value), desc: v.$description });
    else if (v && typeof v === 'object') walk(v, [...path, k], out);
  }
  return out;
}
function block(selector, file, title) {
  const t = read(file);
  const ext = t.$extensions?.['com.ibm.gallium'] || {};
  const lines = walk(t).map((d) => `  --cf-${d.name}:${d.value};${d.desc ? ` /* ${d.desc} */` : ''}`);
  if (ext.colorScheme) lines.unshift(`  color-scheme:${ext.colorScheme};`);
  return `/* ---------- ${title} ---------- */\n${selector}{\n${lines.join('\n')}\n}`;
}

const generated = [
  `${START} · generated by \`npm run tokens\` from tokens/*.tokens.json — edit the JSON, not this block */`,
  block(':root', 'tokens/primitive.tokens.json', '1. PRIMITIVES (IBM palette; components never use these)'),
  block(':root,[data-cf-theme="white"]', 'tokens/themes/white.tokens.json', '2. SEMANTIC TOKENS · White'),
  block('[data-cf-theme="g100"]', 'tokens/themes/g100.tokens.json', '2b. SEMANTIC TOKENS · G100'),
  block(':root', 'tokens/scale.tokens.json', '3. SCALE TOKENS'),
  END,
].join('\n');

const css = readFileSync('gallium.css', 'utf8');
const a = css.indexOf(START), b = css.indexOf(END);
if (a < 0 || b < 0) { console.error('✖ gallium.css has no tokens:start / tokens:end markers'); process.exit(1); }
const next = css.slice(0, a) + generated + css.slice(b + END.length);
if (CHECK) {
  if (next !== css) { console.error('✖ gallium.css token block is out of date — run: npm run tokens'); process.exit(1); }
  console.log('✓ gallium.css token block matches tokens/');
} else {
  writeFileSync('gallium.css', next);
  console.log('✓ gallium.css token block regenerated from tokens/');
}
